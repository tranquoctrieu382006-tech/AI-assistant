"""Create the held-out M2 fingerprint. Run and commit it before evaluation."""
import hashlib
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HELDOUT = ROOT / "eval/rag_heldout_m1.json"
M1_MANIFEST = ROOT / "eval/development_manifest_m1.json"
OUTPUT = ROOT / "eval/heldout_manifest_m2.json"
M1_COMMIT = "4c663793007d46b30ed7a7854e543110af437aff"
EVALUATOR_FILES = [
    "scripts/evaluate_rag_heldout.py",
    "scripts/write_heldout_manifest.py",
    "tests/test_rag_heldout.py",
]


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    cases = json.loads(HELDOUT.read_text(encoding="utf-8"))
    counts = dict(sorted(Counter(case["category"] for case in cases).items()))
    manifest = {
        "manifest": "M2",
        "m1_commit": M1_COMMIT,
        "m1_manifest_sha256": digest(M1_MANIFEST),
        "heldout_path": "eval/rag_heldout_m1.json",
        "heldout_sha256": digest(HELDOUT),
        "case_count": len(cases),
        "category_counts": counts,
        "top_k": 5,
        "relevance_cutoff": 0.5,
        "primary_metric": "context_recall@5",
        "risk_metric": "false_positive_count_and_rate_by_abstention_type",
        "evaluation_mode": "aggregate-only; no per-case results or question text",
        "question_authoring_note": (
            "Generated by Codex after M1 was frozen; no independent human writer/reviewer. "
            "Treat this as exploratory and consider independent review before production claims."
        ),
        "heldout_evaluator_code": {
            relative: digest(ROOT / relative) for relative in EVALUATOR_FILES
        },
    }
    OUTPUT.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT).as_posix()}")
    print(f"Held-out cases: {len(cases)}; categories: {counts}")


if __name__ == "__main__":
    main()
