"""Create the held-out M2 fingerprint. Run and commit it before evaluation."""
import json
import argparse
from collections import Counter
from pathlib import Path
from scripts.manifest_hashing import sha256_file

ROOT = Path(__file__).resolve().parents[1]
HELDOUT = ROOT / "eval/rag_heldout_m1.json"
M1_MANIFEST = ROOT / "eval/development_manifest_m1.json"
OUTPUT = ROOT / "eval/heldout_manifest_m2.json"
M1_COMMIT = "4c663793007d46b30ed7a7854e543110af437aff"
EVALUATOR_FILES = [
    "scripts/evaluate_rag_heldout.py",
    "scripts/write_heldout_manifest.py",
    "tests/test_rag_heldout.py",
]


def main(
    output_path: Path = OUTPUT,
    *,
    label: str = "M2",
    m1_manifest: Path = M1_MANIFEST,
    m1_commit: str = M1_COMMIT,
) -> None:
    if output_path.exists():
        raise FileExistsError(
            f"Refusing to overwrite frozen manifest {output_path}; choose a new --output path."
        )
    cases = json.loads(HELDOUT.read_text(encoding="utf-8"))
    counts = dict(sorted(Counter(case["category"] for case in cases).items()))
    manifest = {
        "manifest": label,
        "hash_format": "sha256-canonical-text-lf-v1",
        "m1_commit": m1_commit,
        "m1_manifest_sha256": sha256_file(m1_manifest),
        "m1_manifest_path": m1_manifest.relative_to(ROOT).as_posix(),
        "heldout_path": "eval/rag_heldout_m1.json",
        "heldout_sha256": sha256_file(HELDOUT),
        "case_count": len(cases),
        "category_counts": counts,
        "top_k": 5,
        "relevance_cutoff": 0.5,
        "primary_metric": "context_recall@5",
        "risk_metric": "false_positive_count_and_rate_by_abstention_type",
        "evaluation_mode": "aggregate-only; no per-case results or question text",
        "question_authoring_note": (
            "Generated by Codex after M1 was frozen; no independent human writer/reviewer. "
            "Treat this as exploratory and consider independent review before production claims."
        ),
        "heldout_evaluator_code": {
            relative: sha256_file(ROOT / relative) for relative in EVALUATOR_FILES
        },
    }
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {output_path.relative_to(ROOT).as_posix()}")
    print(f"Held-out cases: {len(cases)}; categories: {counts}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--label", default="M2", help="Manifest label, e.g. M2 or M3.")
    parser.add_argument("--m1-manifest", type=Path, default=M1_MANIFEST)
    parser.add_argument("--m1-commit", default=M1_COMMIT)
    args = parser.parse_args()

    def _abs(path: Path) -> Path:
        return path if path.is_absolute() else ROOT / path

    main(
        _abs(args.output),
        label=args.label,
        m1_manifest=_abs(args.m1_manifest),
        m1_commit=args.m1_commit,
    )
