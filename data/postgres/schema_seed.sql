-- Force UTF-8 so psql works even when Windows has a legacy client encoding.
SET client_encoding TO 'UTF8';
CREATE TABLE categories(category_id INT PRIMARY KEY, name TEXT NOT NULL UNIQUE);
CREATE TABLE suppliers(supplier_id INT PRIMARY KEY, name TEXT NOT NULL, city TEXT NOT NULL);
CREATE TABLE products(product_id INT PRIMARY KEY, sku TEXT NOT NULL UNIQUE, name TEXT NOT NULL, category_id INT NOT NULL REFERENCES categories, supplier_id INT NOT NULL REFERENCES suppliers, unit_price NUMERIC(12,2) NOT NULL CHECK(unit_price>=0), active BOOLEAN NOT NULL DEFAULT TRUE);
CREATE TABLE customers(customer_id INT PRIMARY KEY, full_name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, city TEXT NOT NULL, member_tier TEXT NOT NULL CHECK(member_tier IN ('Đồng','Bạc','Vàng','Kim cương')), joined_on DATE NOT NULL);
CREATE TABLE warehouses(warehouse_id INT PRIMARY KEY, name TEXT NOT NULL, city TEXT NOT NULL);
CREATE TABLE orders(order_id INT PRIMARY KEY, customer_id INT NOT NULL REFERENCES customers, order_date DATE NOT NULL, delivered_date DATE, status TEXT NOT NULL CHECK(status IN ('mới','đã xác nhận','đang giao','đã giao','đã hủy')), shipping_fee NUMERIC(12,2) NOT NULL CHECK(shipping_fee>=0), CHECK(delivered_date IS NULL OR delivered_date>=order_date));
CREATE TABLE order_items(order_item_id INT PRIMARY KEY, order_id INT NOT NULL REFERENCES orders ON DELETE CASCADE, product_id INT NOT NULL REFERENCES products, quantity INT NOT NULL CHECK(quantity>0), unit_price NUMERIC(12,2) NOT NULL CHECK(unit_price>=0), UNIQUE(order_id,product_id));
CREATE TABLE inventory(warehouse_id INT REFERENCES warehouses, product_id INT REFERENCES products, on_hand INT NOT NULL CHECK(on_hand>=0), PRIMARY KEY(warehouse_id,product_id));
CREATE TABLE stock_movements(movement_id INT PRIMARY KEY, warehouse_id INT NOT NULL REFERENCES warehouses, product_id INT NOT NULL REFERENCES products, movement_date DATE NOT NULL, movement_type TEXT NOT NULL CHECK(movement_type IN ('nhập','xuất','điều chỉnh')), quantity INT NOT NULL CHECK(quantity>0), reference TEXT NOT NULL);
